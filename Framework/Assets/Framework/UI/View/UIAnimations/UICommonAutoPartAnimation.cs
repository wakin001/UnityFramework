using DG.Tweening;

namespace Framework
{
    /// <summary>
    /// 共通で自動なよく使うパーツのAnimation
    /// Newとかの点滅するImageの
    /// </summary>
    public class UICommonAutoPartAnimation : MonoBehaviour
    {
        public enum Type
        {
            None,
            NewIcon,    // New Icon
        }

        [SerializeField]
        public Type type;
        // <summary> Awake時に自動実行するかどうか </summary>
        public bool executeOnAwake = true;

        public void Awake()
        {
            if (executeOnAwake)
            {
                DoAnimation();
            }
        }

        /// <summary>
        /// Animationを実行する
        /// </summary>
        public void DoAnimation()
        {
            switch (type)
            {
                case Type.None:
                    break;
                case Type.NewIcon:
                    DoNewIconFlashingAnimation();
                    break;
                default:
                    break;
            }
        }

        /// <summary>
        /// NewIconの点滅Animation
        /// </summary>
